"""Short PDF report: the three synthetic months and the classifier eval."""

from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.backends.backend_pdf import PdfPages

BLUE, ORANGE, GREEN, RED, GREY, INK = "#1f4e5f", "#e07b39", "#3c8d5a", "#b8433a", "#9aa5ab", "#1d2b33"
A4 = (11.69, 8.27)
METHOD_ORDER = ["rule", "learned_rule", "llm", "human", "review", "internal"]
METHOD_COLORS = {
    "rule": BLUE,
    "learned_rule": "#4f8fa3",
    "llm": ORANGE,
    "human": GREEN,
    "review": RED,
    "internal": GREY,
}


def _brl(v: float) -> str:
    return f"R$ {v:,.2f}"


def _table(fig, rect, header, rows, widths, font=9):
    ax = fig.add_axes(rect)
    ax.axis("off")
    t = ax.table(cellText=rows, colLabels=header, loc="upper left", cellLoc="right", colWidths=widths)
    t.auto_set_font_size(False)
    t.set_fontsize(font)
    t.scale(1, 1.4)
    for (r, c), cell in t.get_celld().items():
        cell.set_edgecolor("#e3e7ea")
        cell.get_text().set_parse_math(False)
        if c == 0:
            cell.get_text().set_horizontalalignment("left")
        if r == 0:
            cell.set_facecolor(BLUE)
            cell.get_text().set_color("white")
            cell.get_text().set_weight("bold")


def _method_share(month: dict) -> dict[str, int]:
    return {m["method"]: m["rows"] for m in month["methods"]}


def write(path: Path, months: list[dict], ev: dict, reimport: dict | None = None, png: Path | None = None) -> Path:
    with PdfPages(path, metadata={"CreationDate": None}) as pdf:  # no timestamp: same input, same file
        fig = plt.figure(figsize=A4)
        fig.text(0.05, 0.95, "Personal finance automation - report", fontsize=16, weight="bold", color=BLUE, va="top")
        fig.text(
            0.05,
            0.905,
            "Synthetic data generated by generate_data.py. Three monthly bank statements.",
            fontsize=9,
            color=GREY,
            va="top",
        )
        rows = []
        for m in months:
            share = _method_share(m)
            classified = sum(v for k, v in share.items() if k != "internal")
            by_rule = share.get("rule", 0) + share.get("learned_rule", 0)
            rows.append(
                [
                    m["month"],
                    str(m["rows"]),
                    _brl(m["income"]),
                    _brl(m["expenses"]),
                    _brl(m["net_savings"]),
                    f"{m['savings_rate']:.1%}",
                    f"{by_rule / classified:.0%}",
                    f"{share.get('llm', 0) / classified:.0%}",
                    str(share.get("review", 0)),
                    "yes" if m["reconciled"] else "NO",
                ]
            )
        _table(
            fig,
            [0.05, 0.62, 0.9, 0.22],
            [
                "Month",
                "Rows",
                "Income",
                "Expenses",
                "Savings",
                "Savings rate",
                "By rules",
                "By the LLM",
                "In review",
                "Balance check",
            ],
            rows,
            [0.08, 0.06, 0.12, 0.12, 0.12, 0.1, 0.09, 0.1, 0.09, 0.12],
        )
        ax = fig.add_axes([0.06, 0.1, 0.4, 0.46])
        x = range(len(months))
        ax.bar([i - 0.2 for i in x], [m["income"] for m in months], width=0.4, color=GREEN, label="income")
        ax.bar([i + 0.2 for i in x], [-m["expenses"] for m in months], width=0.4, color=RED, label="expenses")
        ax.set_xticks(list(x), [m["month"] for m in months])
        ax.set_ylabel("R\\$ per month")
        ax.set_title("Income and expenses", loc="left", weight="bold", fontsize=11)
        ax.legend(frameon=False, fontsize=8)
        ax2 = fig.add_axes([0.55, 0.13, 0.4, 0.43])
        bottom = [0] * len(months)
        for meth in METHOD_ORDER:
            vals = [_method_share(m).get(meth, 0) for m in months]
            if any(vals):
                ax2.bar(list(x), vals, bottom=bottom, color=METHOD_COLORS[meth], label=meth.replace("_", " "))
                bottom = [b + v for b, v in zip(bottom, vals)]
        ax2.set_xticks(list(x), [m["month"] for m in months])
        ax2.set_ylabel("rows")
        ax2.set_title("How each row was classified", loc="left", weight="bold", fontsize=11)
        ax2.legend(frameon=False, fontsize=8, ncol=3, loc="upper center", bbox_to_anchor=(0.5, -0.08))
        if png:
            fig.savefig(png, dpi=90)
        pdf.savefig(fig)
        plt.close(fig)

        fig = plt.figure(figsize=A4)
        last = months[-1]
        fig.text(
            0.05,
            0.95,
            f"Expenses by category ({last['month']}) and classifier eval",
            fontsize=16,
            weight="bold",
            color=BLUE,
            va="top",
        )
        cats = sorted(
            (c for c in last["categories"] if c["total"] < 0 and c["category"] != "(in review)"),
            key=lambda c: c["total"],
        )
        ax = fig.add_axes([0.2, 0.1, 0.3, 0.75])
        ax.barh([c["category"] for c in cats][::-1], [-c["total"] for c in cats][::-1], color=BLUE)
        ax.set_xlabel("R\\$")
        acc = ev.get("accuracy") or 0
        auto_acc = ev.get("auto_accuracy") or 0
        items = [
            ["Shops with a known right category (answer key)", str(ev["golden"])],
            ["Accuracy, all answers", f"{acc:.1%}"],
            ["Applied automatically (high confidence)", str(ev["auto_applied"])],
            ["Accuracy of those", f"{auto_acc:.1%}"],
            ["Sent to human review", str(ev["sent_to_review"])],
            ["Errors caught by review", str(ev["errors_caught_by_review"])],
            ["Wrong but confident (used without review)", str(len(ev.get("confident_errors", [])))],
        ]
        if reimport:
            items.append(
                ["Month imported twice: new rows / duplicates", f"{reimport['new_rows']} / {reimport['duplicates']}"]
            )
        _table(fig, [0.56, 0.55, 0.4, 0.3], ["Eval and checks", "Result"], items, [0.8, 0.2])
        errors = [
            f"{r['description']}\n  expected {r['expected']}, got {r['predicted']} (confidence {r['confidence']:.2f})"
            for r in ev.get("rows", [])
            if not r["correct"]
        ]
        fig.text(
            0.56,
            0.5,
            "Wrong answers:\n" + ("\n".join(f"- {e}" for e in errors) if errors else "none"),
            fontsize=9,
            color=INK,
            va="top",
            parse_math=False,
        )
        pending = {r["description"]: r for m in months for r in m["in_review"]}.values()
        pending = [f"{r['description']} ({r['llm_category']}, {r['confidence']:.2f})" for r in pending]
        waiting = "\n".join(f"- {x}" for x in pending) if pending else "none"
        fig.text(
            0.56,
            0.4,
            "Waiting for a person:\n" + waiting,
            fontsize=9,
            color=INK,
            va="top",
            parse_math=False,
            wrap=False,
        )
        pdf.savefig(fig)
        plt.close(fig)
    return path
